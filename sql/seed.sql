
DROP TABLE IF EXISTS animals;
DROP TABLE IF EXISTS reserves;

CREATE TABLE reserves (
    id          INTEGER PRIMARY KEY,
    name        VARCHAR(100) NOT NULL,
    region      VARCHAR(50)  NOT NULL,
    latitude    FLOAT        NOT NULL,
    longitude   FLOAT        NOT NULL,
    description TEXT
);

CREATE TABLE animals (
    id                   INTEGER PRIMARY KEY,
    collar_code          VARCHAR(20)  NOT NULL UNIQUE,
    species              VARCHAR(100) NOT NULL,
    nickname             VARCHAR(50)  NOT NULL,
    endangered_level     INTEGER      NOT NULL CHECK (endangered_level BETWEEN 1 AND 5),
    last_seen_reserve_id INTEGER      NOT NULL,
    FOREIGN KEY (last_seen_reserve_id) REFERENCES reserves(id)
);

